int put_num_text(dbf *t, u16 f, const char *s)
{
    const dbf_field *fd;
    const char *dot;
    size_t n;

    fd = dbf_field_at(t, f);
    n = strlen(s);
    dot = strchr(s, '.');
    if (n > fd->len || (fd->dec == 0 ? dot != NULL
                        : dot == NULL || strlen(dot + 1) != fd->dec))
        return DBF_EARG;
    memset(dbf_recbuf(t) + fd->offset, ' ', fd->len);
    memcpy(dbf_recbuf(t) + fd->offset + (fd->len - n), s, n);
    return DBF_OK;
}

/* Store text s at the start of field f, which is blank, as it stands. */
static int put_raw_text(dbf *t, u16 f, const char *s)
{
    const dbf_field *fd;

    fd = dbf_field_at(t, f);
    if (strlen(s) > fd->len)
        return DBF_EARG;
    memcpy(dbf_recbuf(t) + fd->offset, s, strlen(s));
    return DBF_OK;
}

int make_fixture(dbf **out)
{
    dbf *t;
    int rc;
    u16 r;
    u16 f;
    const char *s;

    *out = NULL;
    dbf_set_today(2026, 10, 8);
    rc = dbf_create(tfs_path("KXFIX.DBF", ""), g_fx_fields, FX_NFIELDS);
    if (rc != DBF_OK)
        return rc;
    rc = dbf_open(&t, tfs_path("KXFIX.DBF", ""), DBF_RDWR);
    if (rc != DBF_OK)
        return rc;
    for (r = 0; r < FX_NRECS && rc == DBF_OK; r++) {
        dbf_blank(t);
        for (f = 0; f < FX_NFIELDS && rc == DBF_OK; f++) {
            s = g_fx[r][f];
            if (*s == '\0')
                rc = dbf_put_blank(t, f);
            else if (*s == '=')
                rc = put_raw_text(t, f, s + 1);
            else if (g_fx_fields[f].type == 'N')
                rc = put_num_text(t, f, s);
            else
                rc = dbf_put_str(t, f, s);
        }
        if (rc == DBF_OK)
            rc = dbf_append(t);
    }
    if (rc == DBF_OK)
        rc = dbf_flush(t);
    if (rc != DBF_OK) {
        dbf_close(t);
        return rc;
    }
    *out = t;
    return DBF_OK;
}
