SIZE = 16


def grayed(rows):
    """The grayed form of the glyph rows, as this file's header says."""
    return [''.join('D' if ch not in '.W' and (x + y) % 2 == 0 else '.'
                    for x, ch in enumerate(row))
            for y, row in enumerate(rows)]


def bmp(glyphs):
    """The bytes of the bitmap file of glyphs, each a list of rows: the
    file header, the bitmap's header, the palette and the pixels, bottom
    row first, a row a whole number of 32-bit words."""
    rows = []
    for g in glyphs:
        rows += g + grayed(g)
    pixels = b''
    for row in reversed(rows):
        ix = [COLOURS[ch] for ch in row]
        pixels += bytes(ix[x] << 4 | ix[x + 1] for x in range(0, SIZE, 2))
    info = (struct.pack('<IiiHHIIiiII', 40, SIZE, len(rows), 1, 4, 0,
                        len(pixels), 0, 0, 0, 0) +
            b''.join(struct.pack('<BBBB', b, g, r, 0)
                     for r, g, b in PALETTE))
    return (struct.pack('<2sIHHI', b'BM', 14 + len(info) + len(pixels), 0,
                        0, 14 + len(info)) +
            info + pixels)


def main(argv):
    if len(argv) != 1:
        sys.stderr.write('invtool: one output file expected\n' +
                         __doc__.split('\n\n')[1] + '\n')
        return 2
    glyphs = [art.split() for _, art in GLYPHS]
    for (name, _), rows in zip(GLYPHS, glyphs):
        if len(rows) != SIZE or any(len(r) != SIZE or set(r) - set(COLOURS)
                                    for r in rows):
            sys.stderr.write('invtool: %s is not %d rows of %d pixels\n' %
                             (name, SIZE, SIZE))
            return 1
    try:
        with open(argv[0], 'wb') as f:
            f.write(bmp(glyphs))
    except OSError as e:
        sys.stderr.write('invtool: %s\n' % e)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
