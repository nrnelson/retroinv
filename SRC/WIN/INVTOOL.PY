"""INVTOOL.PY - write the glyphs of INVWIN's tool bar, drawn below as
text, as a bitmap file.

usage: python3 -I SRC/WIN/INVTOOL.PY OUT.BMP

GLYPHS holds the pictures of the tool bar's buttons (SRC/WIN/WTOOL.H),
in the order of its buttons: each as 16 rows of 16 characters, top row
first, a letter of COLOURS for each pixel, '.' for the button's face.
Outlines are black, so that a glyph still reads on a monochrome display,
where each colour becomes black or white.

OUT.BMP is a Windows 3.0 bitmap, one column of glyphs 16 pixels wide in
the 16 colours of the VGA, the order of PALETTE: each glyph, then its
grayed form, which this program draws from the glyph: every pixel of it
that is neither '.' nor 'W' and stands where its row and column add up
to an even number is dark grey, every other the face.  WTOOL.C draws
light grey as the button's face and dark grey as grayed text, in the
colours the Control Panel sets.  The resource compiler binds the file
into a program from its resource script as the bitmap named WTOOL.

Exit status: 0 when the file is written, 1 when it cannot be, 2 on a
usage error.
"""
