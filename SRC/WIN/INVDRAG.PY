"""INVDRAG.PY - write INVWIN's drag cursor, drawn below as text, as a .CUR.

usage: python3 -I SRC/WIN/INVDRAG.PY OUT.CUR

The cursor shows while an item of the contents is dragged onto the
location tree: the arrow of Windows' own pointer, its hot spot at the tip
(HOTSPOT), and below it to the right an item's card, a white label with
two lines of text.  CURSOR holds it as 32 rows of 32 characters, top row
first: 'K' black, 'W' white, '.' where the screen shows through.

OUT.CUR is a Windows 3.0 cursor file: one monochrome image of 32 x 32
pixels, its AND mask set at each '.', its XOR bitmap at each 'W'.  The
resource compiler binds it into INVWIN.EXE from SRC/WIN/INVWIN.RC.

Exit status: 0 when the file is written, 1 when it cannot be, 2 on a
usage error.
"""
import struct
import sys

CURSOR = '''
K...............................
KK..............................
KWK.............................
KWWK............................
KWWWK...........................
KWWWWK..........................
KWWWWWK.........................
KWWWWWWK........................
KWWWWWWWK.......................
KWWWWWWWWK......................
KWWWWWKKKKK.....................
KWWKWWK.........................
KWK.KWWK........................
KK..KWWK........................
K....KWWK.......................
.....KWWK.......................
......KKKKKKKKKKKKKK............
......KWWWWWWWWWWWWK............
......KWKKKKKKKKKKWK............
......KWWWWWWWWWWWWK............
......KWKKKKKKKWWWWK............
......KWWWWWWWWWWWWK............
......KKKKKKKKKKKKKK............
................................
................................
................................
................................
................................
................................
................................
................................
................................
'''

SIZE = 32
HOTSPOT = (0, 0)


def cur(rows):
    """The bytes of the cursor file of rows: the directory, then the
    image, a header, the two colours, the XOR bitmap and the AND mask,
    both bottom row first, a row of each one 32-bit word."""
    xor = b''
    mask = b''
    for row in reversed(rows):
        white = 0
        clear = 0
        for ch in row:
            white = white << 1 | (ch == 'W')
            clear = clear << 1 | (ch == '.')
        xor += struct.pack('>I', white)
        mask += struct.pack('>I', clear)
    image = (struct.pack('<IiiHHIIiiII', 40, SIZE, 2 * SIZE, 1, 1, 0,
                         len(xor) + len(mask), 0, 0, 0, 0) +
             struct.pack('<BBBBBBBB', 0, 0, 0, 0, 255, 255, 255, 0) +
             xor + mask)
    return (struct.pack('<HHH', 0, 2, 1) +
            struct.pack('<BBBBHHII', SIZE, SIZE, 0, 0, HOTSPOT[0],
                        HOTSPOT[1], len(image), 6 + 16) +
            image)


def main(argv):
    if len(argv) != 1:
        sys.stderr.write('invdrag: one output file expected\n' +
                         __doc__.split('\n\n')[1] + '\n')
        return 2
    rows = CURSOR.split()
    if len(rows) != SIZE or any(len(r) != SIZE or set(r) - set('.KW')
                                for r in rows):
        sys.stderr.write('invdrag: CURSOR is not %d rows of %d pixels\n' %
                         (SIZE, SIZE))
        return 1
    try:
        with open(argv[0], 'wb') as f:
            f.write(cur(rows))
    except OSError as e:
        sys.stderr.write('invdrag: %s\n' % e)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
